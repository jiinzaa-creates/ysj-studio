-- YSJ Studio — D1 schema (migration 0002)
-- Contact-form messages. Backup store for POST /api/contact (see
-- functions/api/contact.js). The endpoint works WITHOUT this table — the
-- insert is best-effort and skipped when D1 is missing or the table
-- does not exist yet.
--
-- Apply once D1 'jinza-db' is provisioned:
--   npx wrangler d1 execute jinza-db --file migrations/0002_contact_messages.sql --remote
--
-- NOTE (verified 2026-11-06): D1 is NOT provisioned in the production
-- Cloudflare account yet (GET /api/beats returns 501 "M3 provisioning
-- pending"). Do not assume this table exists in production.

CREATE TABLE IF NOT EXISTS contact_messages (
  id          TEXT PRIMARY KEY,            -- 'cm_...' generated by the function
  created_at  TEXT NOT NULL,               -- UTC ISO-8601
  topic       TEXT NOT NULL,               -- one of the contact-form topics
  name        TEXT NOT NULL,
  email       TEXT NOT NULL,
  message     TEXT NOT NULL,
  ip_hash     TEXT,                        -- sha256 of the submitter IP, never raw
  email_sent  INTEGER NOT NULL DEFAULT 0,  -- 1 when MailChannels accepted (202)
  handled_at  TEXT,                        -- set when the studio replies
  notes       TEXT
);
CREATE INDEX IF NOT EXISTS idx_contact_messages_created ON contact_messages(created_at);
CREATE INDEX IF NOT EXISTS idx_contact_messages_ip_hour ON contact_messages(ip_hash, created_at);
