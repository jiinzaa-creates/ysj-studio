// YSJ Studio beat store — catalog seed generator.
//
// Reads the 11 beats + 4 approved license tiers from
// public/assets/js/catalog.js and prints idempotent seed SQL to stdout.
//
// Run:
//   node scripts/seed.mjs > scripts/seed.sql
//   npx wrangler d1 execute jinza-db --file scripts/seed.sql --remote
//   (use --local instead of --remote to seed local dev D1)
//
// Idempotency: every statement is INSERT OR IGNORE, so re-running the seed
// never duplicates rows. Re-run after editing catalog.js to pick up changes.
//
// Why string literals instead of bound parameters: `wrangler d1 execute --file`
// does not support bound parameters. All values below are escaped by sqlLit()
// (single quotes doubled) and validated (slugs, integers) before use. The live
// API layer (functions/_lib/db.js) always uses parameterized statements.

import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { BEATS, LICENSES } = require("../public/assets/js/catalog.js");

function sqlLit(v) {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") {
    if (!Number.isFinite(v)) throw new Error(`non-finite number: ${v}`);
    return String(v);
  }
  if (typeof v !== "string") throw new Error(`unsupported seed value type: ${typeof v}`);
  return "'" + v.replace(/'/g, "''") + "'";
}

function slugToId(prefix, slug) {
  if (!/^[a-z0-9-]{1,60}$/.test(slug)) throw new Error(`bad slug: ${slug}`);
  return `${prefix}${slug.replace(/-/g, "_")}`;
}

const out = [];
out.push("-- YSJ Studio catalog seed — generated by scripts/seed.mjs");
out.push("-- Idempotent: safe to re-run (INSERT OR IGNORE).");
out.push("");

/* 1. License terms (DRAFT — owner has not approved final legal terms). */
out.push("-- license_terms (status 'draft' until owner approves final terms)");
for (const t of LICENSES) {
  const version = `${t.id}-v1`;
  const body =
    `# ${t.name} — DRAFT TERMS (v1)\n\n` +
    `> DRAFT — pending owner review. Do not treat as final legal terms.\n\n` +
    `Deliverable: ${t.deliverable}.\n` +
    (t.exclusive
      ? `Exclusive: full ownership transfer of the instrumental; beat is retired from sale after purchase.`
      : `Non-exclusive: the beat remains available for license to other artists.`);
  out.push(
    `INSERT OR IGNORE INTO license_terms (version, tier, title, body_md, status) VALUES (${[
      sqlLit(version),
      sqlLit(t.id),
      sqlLit(`${t.name} — Draft Terms`),
      sqlLit(body),
      sqlLit("draft"),
    ].join(", ")});`
  );
}
out.push("");

/* 2. Beats — all published (matches the M2 storefront). */
out.push("-- beats");
for (const b of BEATS) {
  const id = slugToId("bt_", b.slug);
  out.push(
    `INSERT OR IGNORE INTO beats (id, slug, title, description, genre, mood, bpm, musical_key, artwork_r2_key, preview_r2_key, status, featured) VALUES (${[
      sqlLit(id),
      sqlLit(b.slug),
      sqlLit(b.title),
      sqlLit(b.pocket || null), // marketing pocket → description
      sqlLit(b.genre),
      sqlLit(b.mood),
      b.bpm === null || b.bpm === undefined ? "NULL" : String(Math.trunc(b.bpm)),
      sqlLit(b.key),
      sqlLit(`covers/${b.slug}.jpg`), // public R2 layout mirrors public/assets
      sqlLit(`previews/${b.slug}.mp3`),
      sqlLit("published"),
      b.featured ? "1" : "0",
    ].join(", ")});`
  );
}
out.push("");

/* 3. Licenses — one row per beat × tier. Exclusive = offer-only (price NULL). */
out.push("-- licenses (4 tiers × 11 beats)");
for (const b of BEATS) {
  const beatId = slugToId("bt_", b.slug);
  for (const t of LICENSES) {
    const licId = `lic_${b.slug.replace(/-/g, "_")}_${t.id}`;
    out.push(
      `INSERT OR IGNORE INTO licenses (id, beat_id, tier, name, price_cents, currency, exclusive, terms_version, deliverable, active) VALUES (${[
        sqlLit(licId),
        sqlLit(beatId),
        sqlLit(t.id),
        sqlLit(t.name),
        t.priceCents === null || t.priceCents === undefined ? "NULL" : String(Math.trunc(t.priceCents)),
        sqlLit("usd"),
        t.exclusive ? "1" : "0",
        sqlLit(`${t.id}-v1`),
        sqlLit(t.deliverable),
        "1",
      ].join(", ")});`
    );
  }
}
out.push("");
out.push(`-- Done: ${BEATS.length} beats, ${LICENSES.length} terms, ${BEATS.length * LICENSES.length} license rows.`);

console.log(out.join("\n"));
